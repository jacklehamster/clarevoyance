#!/usr/bin/env python3
"""gen_font.py — generates art/font.png and src/game/font_metrics.h.

art/font.png is the bitmap font sheet used by the game-layer text helpers
(src/game/text.{h,cpp}). Layout: 16 cols x 6 rows of CELL x CELL cells (96
cells), covering ASCII 32 ("space") through 127 in order — cell index =
ascii - 32, the same flat-index convention as every other sprite sheet.

Glyphs are white (so a tint can recolour them) on a transparent background,
drawn with Pillow's built-in scalable default font — no font file needed. Every
glyph sits on ONE shared baseline and is centred horizontally in its cell, so
a string laid out cell by cell reads as a line of text (a full stop sits at the
bottom, a "g" hangs below).

src/game/font_metrics.h records how wide each glyph really is (its advance, as
a fraction of the cell), which is what lets makeTextBlock space letters
proportionally instead of on a typewriter grid.

Needs Pillow >= 10.1:  python3 scripts/gen_font.py   (from the repo root)
"""
from PIL import Image, ImageDraw, ImageFont

COLS = 16
ROWS = 6
CELL = 32
FONT_SIZE = 23
FIRST_ASCII = 32
NUM_GLYPHS = COLS * ROWS   # 96 → ASCII 32..127 inclusive

img = Image.new("RGBA", (COLS * CELL, ROWS * CELL), (0, 0, 0, 0))
draw = ImageDraw.Draw(img)
font = ImageFont.load_default(size=FONT_SIZE)

ascent, descent = font.getmetrics()
assert ascent + descent <= CELL, "font too tall for the cell"
baseline = (CELL - (ascent + descent)) // 2 + ascent

advances = []
for i in range(NUM_GLYPHS):
    ch = chr(FIRST_ASCII + i)
    cx = (i % COLS) * CELL
    cy = (i // COLS) * CELL
    if not ch.isprintable():
        advances.append(0.0)
        continue
    advance = font.getlength(ch)
    assert advance <= CELL, "glyph %r wider than the cell" % ch
    advances.append(advance / CELL)
    # "ls" anchor: x is the glyph's left edge, y its baseline.
    draw.text((cx + (CELL - advance) / 2.0, cy + baseline), ch, font=font,
              fill=(255, 255, 255, 255), anchor="ls")

img.save("art/font.png")

with open("src/game/font_metrics.h", "w") as f:
    f.write("// font_metrics.h — GENERATED by scripts/gen_font.py. Do not edit.\n")
    f.write("//\n")
    f.write("// How wide each glyph of art/font.png is: its advance as a fraction of the\n")
    f.write("// (square) glyph cell, indexed by ascii - FONT_FIRST_ASCII. Each glyph is\n")
    f.write("// centred in its cell, so a glyph drawn in a cell of size S belongs at\n")
    f.write("// pen + advance*S/2, and the pen then moves on by advance*S.\n")
    f.write("#pragma once\n\n")
    f.write("namespace cv {\n\n")
    f.write("constexpr float FONT_ADVANCE[%d] = {\n" % NUM_GLYPHS)
    for row in range(0, NUM_GLYPHS, 8):
        chunk = advances[row:row + 8]
        names = "".join(chr(FIRST_ASCII + row + k) if 32 < FIRST_ASCII + row + k < 127 else " "
                        for k in range(len(chunk)))
        f.write("    " + ", ".join("%.4ff" % a for a in chunk) + ",   // " + names.replace("\\", "backslash") + "\n")
    f.write("};\n\n")
    f.write("// Line height that suits the font, as a fraction of the cell.\n")
    f.write("constexpr float FONT_LINE_HEIGHT = %.4ff;\n\n" % ((ascent + descent + 4) / CELL))
    f.write("} // namespace cv\n")

print("wrote art/font.png (%dx%d, %d glyphs, %dx%d cells) and src/game/font_metrics.h"
      % (img.size[0], img.size[1], NUM_GLYPHS, CELL, CELL))
